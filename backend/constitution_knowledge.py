class ConstitutionAssistant:
    """Детерминированный справочник по Конституции Беларуси."""

    def __init__(self) -> None:
        self.article_pattern = re.compile(
            r"(?:ст\.?|стать[яеию])\s*(\d{1,3})", re.IGNORECASE
        )

    def generate_response(self, question: str) -> str:
        clean_question = question.strip()
        lower_question = clean_question.lower()

        if self._is_identity_question(lower_question):
            return IDENTITY_RESPONSE

        if not self._is_constitution_question(lower_question):
            return f"{REFUSAL_MESSAGE} Вы спросили: \"{clean_question}\"."

        article_numbers = self._extract_articles(lower_question)
        if article_numbers:
            return self._build_article_response(article_numbers, clean_question)

        theme = self._detect_theme(lower_question)
        if theme:
            return self._build_theme_response(theme, clean_question)

        return self._build_general_response(clean_question)

    def _is_identity_question(self, text: str) -> bool:
        return any(phrase in text for phrase in IDENTITY_PHRASES)

    def _is_constitution_question(self, text: str) -> bool:
        if self.article_pattern.search(text):
            return True
        return any(keyword in text for keyword in CONSTITUTION_KEYWORDS)

    def _extract_articles(self, text: str) -> List[str]:
        numbers = self.article_pattern.findall(text)
        seen: List[str] = []
        for num in numbers:
            if num not in seen:
                seen.append(num)
        return seen

    def _detect_theme(self, text: str) -> str:
        for theme, keywords in THEME_KEYWORDS.items():
            if any(keyword in text for keyword in keywords):
                return theme
        return ""

    def _build_article_response(self, article_numbers: List[str], question: str) -> str:
        lines = [IDENTITY_INTRO, f"Вы спросили: \"{question}\"."]

        for number in article_numbers:
            summary = ARTICLE_SUMMARIES.get(number)
            if summary:
                lines.append(f"Статья {number} Конституции Республики Беларусь{summary}")
            else:
                lines.append(
                    f"Статья {number} Конституции Республики Беларусь относится к "
                    "разделу правового статуса граждан и раскрывает отдельные гарантии."
                )

        lines.append(self._reference_text(article_numbers))
        return "\n\n".join(line for line in lines if line)

    def _build_theme_response(self, theme: str, question: str) -> str:
        theme_data = THEME_RESPONSES.get(theme)
        if not theme_data:
            return self._build_general_response(question)

        lines = [
            IDENTITY_INTRO,
            f"Вы спросили: \"{question}\".",
            theme_data["text"],
            self._reference_text(theme_data["articles"]),
        ]
        return "\n\n".join(line for line in lines if line)

    def _build_general_response(self, question: str) -> str:
        lines = [
            IDENTITY_INTRO,
            f"Вы спросили: \"{question}\".",
            GENERAL_OVERVIEW_TEXT,
            self._reference_text(GENERAL_OVERVIEW_ARTICLES),
        ]
        return "\n\n".join(lines)

    @staticmethod
    def _reference_text(articles: List[str]) -> str:
        if not articles:
            return ""
        if len(articles) == 1:
            return (
                f"Справка: статья {articles[0]} Конституции Республики Беларусь "
                "подробно раскрывает этот вопрос."
            )
        joined = ", ".join(articles)
        return (
            f"Справка: статьи {joined} Конституции Республики Беларусь закрепляют "
            "эти нормы."
        )
